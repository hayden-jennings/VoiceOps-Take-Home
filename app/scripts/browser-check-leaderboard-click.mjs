import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 900, height: 900 } });
await page.goto("http://localhost:3000/dashboard-demo");
await page.waitForSelector(".recharts-wrapper", { timeout: 10000 });
await page.getByText("skill_scores + leaderboard, repName set", { exact: true }).click();
await page.waitForSelector("text=/Leaderboard/", { timeout: 10000 });
await page.waitForTimeout(500);
await page.getByRole("button", { name: /Maria Garcia/ }).click();
await page.waitForTimeout(400);
const paramsText = await page.locator("text=/params:/").textContent();
console.log("params after clicking Maria Garcia in leaderboard:", paramsText);
await browser.close();
